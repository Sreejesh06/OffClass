export function Login() {
  const navigate = useNavigate();
  const location = useLocation();
  const { login, isLoading } = useAuth();

  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [error, setError] = useState<string | null>(null);

  const from = location.state?.from?.pathname || "/profile";

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);

    if (!email) {
      setError("Email is required");
      return;
    }

    if (!email.endsWith('@sece.ac.in')) {
      setError("Only @sece.ac.in college emails are permitted.");
      return;
    }

    try {
      await login(email);
      navigate(from, { replace: true });
    } catch (err) {
      setError("Authentication failed.");
    }
  };

  return (
    <div style={{ display: 'flex', minHeight: '100vh', backgroundColor: '#B8B8B8', alignItems: 'center', justifyContent: 'center', padding: '2rem' }}>
      
      {/* Main Container mirroring the image */}
      <div style={{ display: 'flex', width: '100%', maxWidth: '1100px', height: '650px', backgroundColor: '#fff', boxShadow: '0 25px 50px -12px rgba(0, 0, 0, 0.25)', overflow: 'hidden' }}>
        
        {/* Left Column: Form */}
        <div style={{ flex: '1', display: 'flex', flexDirection: 'column', padding: '4rem', backgroundColor: '#ffffff', color: '#000000', position: 'relative' }}>
          
          <div style={{ display: 'flex', justifyContent: 'center', marginBottom: '3rem' }}>
            {/* Lightning bolt logo from the image */}
            <svg width="24" height="24" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg">
              <path d="M13 2L3 14H12L11 22L21 10H12L13 2Z" fill="#000000"/>
            </svg>
          </div>

          <div style={{ flex: '1', display: 'flex', flexDirection: 'column', alignItems: 'center', maxWidth: '360px', width: '100%', margin: '0 auto' }}>
            <h1 style={{ marginBottom: '0.5rem', fontFamily: 'var(--font-h1)', fontSize: '2.5rem', color: '#000', fontWeight: 400, textAlign: 'center' }}>Welcome back!</h1>
            <p style={{ color: '#666', marginBottom: '2.5rem', fontFamily: 'var(--font-body)', fontSize: '0.9rem', textAlign: 'center' }}>
              Access your department dossier.
            </p>

            <form onSubmit={handleSubmit} style={{ display: 'flex', flexDirection: 'column', gap: '1.25rem', width: '100%' }} noValidate>
              
              <div style={{ display: 'flex', flexDirection: 'column', gap: '0.5rem' }}>
                <label htmlFor="email" style={{ fontSize: '0.8rem', fontWeight: 600, color: '#000' }}>College Email</label>
                <input 
                  id="email"
                  type="email" 
                  value={email}
                  onChange={(e) => setEmail(e.target.value)}
                  placeholder="student@sece.ac.in"
                  aria-invalid={error ? "true" : "false"}
                  style={{
                    padding: '0.875rem 1rem',
                    backgroundColor: '#fff',
                    border: `1px solid ${error ? '#e11d48' : '#E2E8F0'}`,
                    borderRadius: '0.5rem',
                    color: '#000',
                    fontFamily: 'var(--font-mono)',
                    fontSize: '0.875rem',
                    outline: 'none',
                    transition: 'border-color 0.2s ease',
                    width: '100%',
                    boxSizing: 'border-box'
                  }}
                />
              </div>

              <div style={{ display: 'flex', flexDirection: 'column', gap: '0.5rem' }}>
                <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                  <label htmlFor="password" style={{ fontSize: '0.8rem', fontWeight: 600, color: '#000' }}>Password</label>
                  <a href="#" style={{ fontSize: '0.75rem', color: '#666', textDecoration: 'none', fontWeight: 500 }}>Forgot Password?</a>
                </div>
                <input 
                  id="password"
                  type="password" 
                  value={password}
                  onChange={(e) => setPassword(e.target.value)}
                  placeholder="Enter your password"
                  aria-invalid={error ? "true" : "false"}
                  style={{
                    padding: '0.875rem 1rem',
                    backgroundColor: '#fff',
                    border: `1px solid ${error ? '#e11d48' : '#E2E8F0'}`,
                    borderRadius: '0.5rem',
                    color: '#000',
                    fontFamily: 'var(--font-mono)',
                    fontSize: '0.875rem',
                    outline: 'none',
                    transition: 'border-color 0.2s ease',
                    width: '100%',
                    boxSizing: 'border-box'
                  }}
                />
              </div>

              {error && (
                <div role="alert" style={{ color: '#e11d48', fontSize: '0.75rem', fontWeight: 500 }}>
                  {error}
                </div>
              )}

              <button 
                type="submit" 
                disabled={isLoading}
                style={{
                  marginTop: '0.5rem',
                  padding: '1rem',
                  backgroundColor: '#000',
                  color: '#fff',
                  border: 'none',
                  borderRadius: '0.5rem',
                  fontWeight: 600,
                  fontSize: '0.875rem',
                  cursor: isLoading ? 'wait' : 'pointer',
                  opacity: isLoading ? 0.7 : 1,
                  transition: 'opacity 0.2s ease',
                  width: '100%'
                }}
              >
                {isLoading ? 'Authenticating...' : 'Sign In'}
              </button>
            </form>
            
            <div style={{ marginTop: '2rem', textAlign: 'center', fontSize: '0.8rem', color: '#666' }}>
              Don't have an account? <a href="#" style={{ color: '#000', fontWeight: 600, textDecoration: 'underline', textUnderlineOffset: '4px' }}>Sign Up</a>
            </div>
          </div>

          <div style={{ position: 'absolute', bottom: '2rem', left: '0', right: '0', display: 'flex', justifyContent: 'center', gap: '1rem', fontSize: '0.7rem', color: '#94A3B8' }}>
            <a href="#" style={{ color: '#94A3B8', textDecoration: 'none' }}>Help</a>
            <span>/</span>
            <a href="#" style={{ color: '#94A3B8', textDecoration: 'none' }}>Terms</a>
            <span>/</span>
            <a href="#" style={{ color: '#94A3B8', textDecoration: 'none' }}>Privacy</a>
          </div>
        </div>

        {/* Right Column: ASCII Art */}
        <div className="desktop-only" style={{ flex: '1', overflow: 'hidden', position: 'relative', backgroundColor: '#F8F9FA' }}>
          <pre style={{ 
            margin: 0,
            color: '#000',
            fontFamily: 'var(--font-mono)',
            fontSize: '5.5px',
            lineHeight: '5.5px',
            height: '100%',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'center',
            userSelect: 'none',
            opacity: 0.9,
            transform: 'scale(1.2)'
          }}>
            {ASCII_ART}
          </pre>
        </div>
      </div>
    </div>
  );
}
